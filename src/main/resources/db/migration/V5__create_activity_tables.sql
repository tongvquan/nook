CREATE TABLE activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    location_id BIGINT REFERENCES locations(id) ON DELETE SET NULL, -- Gắn vị trí (nếu có)

    title VARCHAR(200) NOT NULL,             -- Tên việc (Vd: Check-in công ty, Mua sữa, Đọc sách, Sửa xe)
    description TEXT,                       -- Chi tiết/Ghi chú
    category VARCHAR(50) DEFAULT 'PERSONAL', -- WORK, PERSONAL, HEALTH, FINANCE, LEARNING...

    -- Phân loại bản chất công việc
    type VARCHAR(30) NOT NULL,              -- 'GEOFENCE' (theo vị trí), 'SCHEDULED' (theo giờ), 'ROUTINE' (thói quen), 'BACKLOG' (lúc nào làm cũng được)
    priority INT DEFAULT 2,                 -- 1: Cao, 2: Trung bình, 3: Thấp
    status VARCHAR(20) DEFAULT 'PENDING',   -- 'PENDING', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED'

    -- Điều kiện kích hoạt thời gian (Nếu có)
    due_date TIMESTAMP,                     -- Hạn chót
    start_time TIME,                        -- Khung giờ áp dụng (Vd: 07:30)
    end_time TIME,                          -- Khung giờ kết thúc (Vd: 09:00)
    repeat_rule VARCHAR(50),                -- 'DAILY', 'WEEKLY', 'MONTHLY', NULL (Lặp lại)

    -- Điều kiện kích hoạt vị trí (Nếu có)
    location_event VARCHAR(10),             -- 'ENTER' (Đến nơi mới nhắc), 'EXIT' (Rời đi mới nhắc/cảnh báo)

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);